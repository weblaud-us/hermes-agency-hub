"""Regional presets, and the business profile each tenant's agent reads."""

from __future__ import annotations

from typing import TYPE_CHECKING, Any

import yaml

from .guardrails import lanes_for

if TYPE_CHECKING:  # the renderer also takes test doubles
    from ..clients.models import Client

REGION_PRESETS: dict[str, dict[str, list[str]]] = {
    "bd": {
        "languages": ["bn", "banglish", "en"],
        "channels": ["whatsapp", "messenger"],
        "couriers": ["pathao", "steadfast", "redx"],
        "payments": ["bkash", "nagad", "cash_on_delivery"],
        "integrations": [],
    },
    "global": {
        "languages": ["en"],
        "channels": ["whatsapp", "instagram", "slack"],
        "couriers": ["dhl", "shippo"],
        "payments": ["stripe"],
        "integrations": ["shopify", "woocommerce", "calendly"],
    },
}


def business_profile(client: "Client") -> dict[str, Any] | None:
    """What the agent needs to know to act in this client's market.

    ``None`` for anything that has no business profile to describe.
    """
    region = getattr(client, "region_preset", None)
    mode = getattr(client, "business_mode", None)
    if region is None or mode is None:
        return None

    from .social import effective_brand_kit  # social imports the approval machinery

    lanes = lanes_for(client)
    return {
        "company_name": client.company_name,
        "business_mode": mode.value,
        "niche_template": client.niche_template.value,
        "package_tier": client.package_tier.value,
        "region_preset": region.value,
        "currency": client.currency,
        "onboarding_stage": client.onboarding_stage,
        "autopilot_social": bool(getattr(client, "autopilot_social", True)),
        "brand_kit": effective_brand_kit(client),
        **REGION_PRESETS[region.value],
        "guardrails": {
            lane: [item["key"] for item in lanes if item["lane"] == lane]
            for lane in ("automatic", "owner", "never")
        },
    }


def render_business_profile(client: "Client") -> str:
    profile = business_profile(client)
    if profile is None:
        return ""
    header = (
        "# Generated by the agency hub and rewritten on every re-provision.\n"
        "# Read by the ai-employee-orchestrator skill. Contains no credentials.\n"
    )
    return header + yaml.safe_dump(profile, sort_keys=False, allow_unicode=True)
